<script>
    import Navbar from "../../../Components/Navbar/User.vue";
    import Footer from "../../../Components/Footer.vue";
    import { Head, Link } from '@inertiajs/vue3';
    import VanillaTilt from "vanilla-tilt";
    import { tns } from "tiny-slider";
    import Swal from 'sweetalert2';

    export default {
        components: {
            Head,
            Link,
            Navbar,
            Footer
        },

        props: {
            profile: Object,
            total_activities: Number,
            activities: Array,
            total_programs: Number,
            programs: Array,
            blogs: Array,
            partners: Array,
            testimonials: Array,
        },

        mounted() {
            const elements = document.querySelectorAll('.bg-gradient-myprimary');
            VanillaTilt.init(elements, {
                max: 4,
                speed: 800,
                glare: true,
                "max-glare": 0.2,
            });

            this.initSlider('.activities-slider');
            this.initSlider('.programs-slider');

            document.getElementById('copy-icon').addEventListener('click', this.copyToClipboard);
        },

        methods: {
            formatTagline(text) {
                const parts = text.match(/[A-Z][a-z]+|#[A-Z][a-z]+/g);
                if (!parts || parts.length < 2) return text;

                const lastWord = parts.pop();
                return parts.join('') + '<br>' + lastWord;
            },

            initSlider(container) {
                const element = document.querySelector(container);
                if (!element) return;

                tns({
                    container: container,
                    items: 1,
                    mouseDrag: true,
                    autoplay: true,
                    autoplayTimeout: 3000,
                    controls: false,
                    autoplayButtonOutput: false,
                    responsive: {
                        768: {
                            items: 2
                        },
                        1200: {
                            items: 3
                        }
                    }
                });
            },

            stripTags(html) {
                const div = document.createElement("div");
                div.innerHTML = html;
                return div.textContent || div.innerText || "";
            },

            formatDate(dateStr) {
                const date = new Date(dateStr);
                return new Intl.DateTimeFormat('id-ID', {
                    day: 'numeric',
                    month: 'long',
                    year: 'numeric',
                }).format(date);
            },

            formattedBankName() {
                const map = {
                    BCA: 'Bank Central<br>Asia',
                    BRI: 'Bank Rakyat<br>Indonesia',
                    BNI: 'Bank Negara<br>Indonesia',
                    BTN: 'Bank Tabungan<br>Negara',
                    BSI: 'Bank Syariah<br>Indonesia',
                    Mandiri: ' ',
                };

                const name = this.profile.bank_name;
                return map[name] || this.profile.bank_name;
            },

            copyToClipboard() {
                const bankNumber = document.getElementById('bank-number').innerText;

                navigator.clipboard.writeText(bankNumber).then(() => {
                    Swal.fire({
                        icon: 'success',
                        title: 'Nomor rekening berhasil disalin!',
                        text: 'Setiap langkah kebaikan yang Anda berikan, menjadi bagian dari perjalanan bersama ✨',
                        timer: 3000,
                        timerProgressBar: true,
                        showConfirmButton: false,
                        customClass: {
                            popup: 'swal-custom-icon',
                        }
                    });
                }).catch(err => {
                    Swal.fire({
                        icon: 'error',
                        title: 'Gagal Menyalin!',
                        text: 'Silakan coba lagi.',
                        timer: 2000,
                        timerProgressBar: true,
                        showConfirmButton: false,
                        customClass: {
                            popup: 'swal-custom-icon',
                        }
                    });
                });
            },
        }
    };
</script>


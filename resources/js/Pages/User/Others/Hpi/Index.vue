                    a: 'HPI dirancang bukan hanya untuk pengembangan diri, tapi untuk meningkatkan produktivitas, kualitas keputusan, engagement, dan inovasi. Itu berarti dampaknya langsung terasa pada performa kerja dan kinerja organisasi.',
                },
                {
                    q: 'Kalau saya bukan eksekutif perusahaan, apakah saya cocok ikut?',
                    a: 'Tentu. HPI dirancang untuk profesional, entrepreneur, dan siapa pun yang ingin meningkatkan performa dirinya. Anda akan belajar prinsip yang bisa langsung diterapkan, baik dalam memimpin tim, membangun bisnis, maupun mengelola kehidupan pribadi.',
                },
            ];

            const form = reactive({
                name: '',
                email: '',
                whatsapp: '',
                city: '',
                size: '',
                business_name: '',
                business_field: '',
                position: '',
                problem: '',
                hope: '',
                from: '',
            });

            const resetForm = () => {
                form.name = '';
                form.email = '';
                form.whatsapp = '';
                form.city = '';
                form.size = '';
                form.business_name = '';
                form.business_field = '';
                form.position = '';
                form.problem = '';
                form.hope = '';
                form.from = '';
            };

            const submit = () => {
                const submitBtn = document.querySelector('#submit_button');
                if (submitBtn) {
                    submitBtn.setAttribute('data-kt-indicator', 'on');
                    submitBtn.setAttribute('disabled', true);
                }

                const payload = new FormData();
                payload.append('name', form.name);
                payload.append('email', form.email);
                payload.append('whatsapp', form.whatsapp);
                payload.append('city', form.city);
                payload.append('size', form.size);
                payload.append('business_name', form.business_name);
                payload.append('business_field', form.business_field);
                payload.append('position', form.position);
                payload.append('problem', form.problem);
                payload.append('hope', form.hope);
                payload.append('from', form.from);

                const cleanup = () => {
                    if (submitBtn) {
                        submitBtn.removeAttribute('data-kt-indicator');
                        submitBtn.removeAttribute('disabled');
                    }
                };

                router.post('/hpi', payload, {
                    onSuccess: () => {
                        const waMessage = encodeURIComponent(
                            `*Pendaftaran HPI Baru*\n\n` +
                            `Nama: ${form.name}\n` +
                            `Email: ${form.email}\n` +
                            `WhatsApp: ${form.whatsapp}\n` +
                            `Asal: ${form.city}\n` +
                            `Ukuran Baju: ${form.size}\n` +
                            `Perusahaan/Organisasi: ${form.business_name}\n` +
                            `Bidang Industri: ${form.business_field}\n` +
                            `Jabatan: ${form.position}\n` +
                            `Tantangan: ${form.problem}\n` +
                            `Harapan: ${form.hope}\n` +
                            `Sumber Info: ${form.from}`
                        );
                        const waUrl = `https://wa.me/6282128279702?text=${waMessage}`;

                        const modalCloseBtn = document.querySelector('#close-modal');
                        if (modalCloseBtn) modalCloseBtn.click();
                        resetForm();

                        Swal.fire({
                            icon: 'success',
                            title: 'Pendaftaran Berhasil!',
                            text: 'Terima kasih telah mendaftar High Performing Individual (HPI) Batch 11. Klik tombol di bawah untuk mengonfirmasi pendaftaran Anda ke Admin via WhatsApp.',
                            confirmButtonText: 'Kirim WhatsApp ke Admin',
                            allowOutsideClick: false,
                            allowEscapeKey: false,
                            customClass: {
                                popup: 'swal-custom-icon',
                                confirmButton: 'btn btn-sm btn-myprimary rounded-pill',
                            },
                            buttonsStyling: false,
                        }).then(() => {
                            window.open(waUrl, '_blank');
                            window.location.reload();
                        });
                    },
                    onFinish: cleanup
                });
            }

            return {
                skills,
                benefits,
                testimonials,
                audiences,
                speakers,
                eliteBenefits,
                includes,
                faqs,
                form,
                submit,
                resetForm
            }
        }
    };
</script>

